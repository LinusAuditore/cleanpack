_lang = "en"


def set_lang(code: str) -> None:
    global _lang
    _lang = code if code in STRINGS else "en"


def current_lang() -> str:
    return _lang


def tr(key: str, **kw: object) -> str:
    """返回当前语言的 key 文案并填入 kw；缺项时回退英文或 key 本身。"""
    s = STRINGS.get(_lang, {}).get(key) or STRINGS["en"].get(key, key)
    return s.format(**kw) if kw else s


def detect_lang(locale_names: list[str]) -> str:
    """按 locale_names 的优先顺序返回支持的语言代码；无匹配时回退英文。"""
    for name in locale_names:
        # 去掉 POSIX 形式的编码和修饰（zh_TW.UTF-8、sr@latin）。
        name = name.split(".")[0].split("@")[0]
        # 按子标签精确比较：前缀匹配会把 frr（北弗里西语）误判为法语。
        lang, *subtags = name.replace("_", "-").lower().split("-")
        # 单字母子标签（-u-、-x-）之后是扩展，例如 u-nu-hans 是数字系统，不是文字。
        rest = []
        for tag in subtags:
            if len(tag) == 1:
                break
            rest.append(tag)
        if lang == "zh":
            # 脚本子标签优先于地区，zh-Hans-HK 是香港使用的简体中文。
            if "hans" in rest:
                return "zh_Hans"
            if "hant" in rest or {"tw", "hk", "mo"} & set(rest):
                return "zh_Hant"
            return "zh_Hans"
        if lang in ("fr", "en"):
            return lang
    return "en"
